/**
 * Stroke Contracts & Data Structures
 * Universal currency between Pointer Input, Stroke Smoothing, and the Brush Engines.
 * 100% pure POD interfaces, 1:1 translatable to C++/Rust structs.
 */

/**
 * 2D Vector representation for coordinate math.
 */
export interface Point2D {
  readonly x: number;
  readonly y: number;
}

/**
 * A single normalized point along a stroke path, carrying all sensor data
 * provided by physical input hardware (Apple Pencil, Wacom stylus, touch, mouse).
 */
export interface StrokePoint {
  readonly canvasX: number;        // X coordinate in canvas pixel space
  readonly canvasY: number;        // Y coordinate in canvas pixel space
  readonly pressure: number;       // Normalized pressure: 0.0 (none) to 1.0 (full)
  readonly tiltX: number;          // Horizontal tilt in degrees: -90 to +90
  readonly tiltY: number;          // Vertical tilt in degrees: -90 to +90
  readonly rotation: number;       // Barrel rotation in degrees: 0 to 360
  readonly speed: number;          // Stroke velocity in pixels/second (computed from time delta)
  readonly timeMs: number;         // Timestamp in milliseconds (high-res performance.now or Date.now)
}

/**
 * A pair of consecutive StrokePoints forming one segment.
 */
export interface StrokeSegment {
  readonly startPoint: StrokePoint;
  readonly endPoint: StrokePoint;
}

/**
 * A cubic Bézier curve segment generated by spline fitting.
 * Solves faceting and guarantees C¹ continuity across stroke paths.
 */
export interface CubicBezierSegment {
  readonly p0: Point2D;            // Start anchor point
  readonly c1: Point2D;            // First control handle
  readonly c2: Point2D;            // Second control handle
  readonly p3: Point2D;            // End anchor point
  readonly startPressure: number;  // Pressure at p0 (0.0 - 1.0)
  readonly endPressure: number;    // Pressure at p3 (0.0 - 1.0)
  readonly startTimeMs: number;    // Timestamp at start
  readonly endTimeMs: number;      // Timestamp at end
}

/**
 * Evaluated parameters for a single dab stamp.
 * Calculated by the brush engine after evaluating dynamics curves and spacing.
 */
export interface DabParameters {
  readonly x: number;              // Center X in canvas pixel space
  readonly y: number;              // Center Y in canvas pixel space
  readonly radius: number;         // Dab radius in pixels (diameter / 2)
  readonly opacity: number;        // Final opacity: 0.0 to 1.0
  readonly flow: number;           // Flow factor: 0.0 to 1.0
  readonly hardness: number;       // Edge hardness: 0.0 (Gaussian soft) to 1.0 (hard edge)
  readonly angleRadians: number;   // Tip orientation in radians
  readonly colorR: number;         // Red: 0 to 255
  readonly colorG: number;         // Green: 0 to 255
  readonly colorB: number;         // Blue: 0 to 255
  readonly colorA: number;         // Alpha: 0 to 1
}
