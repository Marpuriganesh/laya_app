import { describe, it, expect, beforeEach } from "vitest";
import { SpringLoadedTracker } from "../spring_loaded_tracker";

describe("SpringLoadedTracker", () => {
  let tracker: SpringLoadedTracker;

  beforeEach(() => {
    tracker = new SpringLoadedTracker(250);
  });

  it("initializes with the specified threshold and clamps boundaries", () => {
    expect(tracker.threshold).toBe(250);

    tracker.setThreshold(30);
    expect(tracker.threshold).toBe(50); // Min clamp

    tracker.setThreshold(5000);
    expect(tracker.threshold).toBe(2000); // Max clamp

    tracker.setThreshold(300);
    expect(tracker.threshold).toBe(300);
  });

  describe("short tap behavior (< threshold)", () => {
    it("switches to target tool permanently when released before threshold", () => {
      // User is painting with brush, taps 'z' for 100ms
      const down = tracker.onKeyDown("z", "zoom", "brush", 1000);
      expect(down.nextTool).toBe("zoom");
      expect(down.changed).toBe(true);

      const up = tracker.onKeyUp("z", 1100); // 100ms elapsed (< 250ms)
      expect(up).not.toBeNull();
      expect(up!.nextTool).toBe("zoom");
      expect(up!.wasTransientReverted).toBe(false);
      expect(tracker.currentHold).toBeNull();
    });
  });

  describe("long hold behavior (>= threshold)", () => {
    it("reverts back to previous tool when released after threshold", () => {
      // User is painting with brush, presses and holds 'z' for 600ms to zoom
      const down = tracker.onKeyDown("z", "zoom", "brush", 1000);
      expect(down.nextTool).toBe("zoom");
      expect(down.changed).toBe(true);

      const up = tracker.onKeyUp("z", 1600); // 600ms elapsed (>= 250ms)
      expect(up).not.toBeNull();
      expect(up!.nextTool).toBe("brush");
      expect(up!.wasTransientReverted).toBe(true);
      expect(up!.changed).toBe(true);
      expect(tracker.currentHold).toBeNull();
    });

    it("works with eraser 'e' hold while painting with brush", () => {
      const down = tracker.onKeyDown("e", "eraser", "brush", 500);
      expect(down.nextTool).toBe("eraser");

      const up = tracker.onKeyUp("e", 1000); // 500ms elapsed
      expect(up!.nextTool).toBe("brush");
      expect(up!.wasTransientReverted).toBe(true);
    });
  });

  describe("OS key repeat handling", () => {
    it("does not reset pressedTimestamp on repeat keydown events", () => {
      // First keydown at 1000ms
      tracker.onKeyDown("z", "zoom", "brush", 1000);

      // Repeat keydowns generated by OS key repeat
      const repeat1 = tracker.onKeyDown("z", "zoom", "zoom", 1200);
      expect(repeat1.changed).toBe(false);

      const repeat2 = tracker.onKeyDown("z", "zoom", "zoom", 1400);
      expect(repeat2.changed).toBe(false);

      // Key released at 1300ms (300ms since initial press at 1000ms)
      const up = tracker.onKeyUp("z", 1300);
      expect(up!.wasTransientReverted).toBe(true);
      expect(up!.nextTool).toBe("brush");
    });
  });

  describe("untracked keys and cancel", () => {
    it("returns null for keyup of an untracked key", () => {
      tracker.onKeyDown("z", "zoom", "brush", 1000);
      const up = tracker.onKeyUp("x", 1100);
      expect(up).toBeNull();
      expect(tracker.currentHold?.key).toBe("z");
    });

    it("reverts to previous tool on cancel (window blur)", () => {
      tracker.onKeyDown("z", "zoom", "brush", 1000);
      const cancelled = tracker.cancel();
      expect(cancelled).not.toBeNull();
      expect(cancelled!.nextTool).toBe("brush");
      expect(cancelled!.wasTransientReverted).toBe(true);
      expect(tracker.currentHold).toBeNull();
    });

    it("returns null on cancel if no key is currently held", () => {
      expect(tracker.cancel()).toBeNull();
    });
  });
});
